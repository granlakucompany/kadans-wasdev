"""Kadans WASDEV — sound. Never captured from the browser: FFmpeg builds it from the spec and the timeline, so it is
sample-exact even when frame capture is slow.

- Voice: one WAV per scene, made by a text-to-speech callable the host app provides (WASDEV: ElevenLabs; a `sample` is cloned with OpenVoice),
  cached by (text, language, gender, sample, engine) — editing one line re-synthesizes only that line.
- Music: generated by FFmpeg itself (aevalsrc) from a mood + seed: chords, bass, pulse. No samples, no rights to clear,
  and every seed gives a different piece. Or a music file of your own.
- Mix: voices placed at their scene, the clips' own sound (trimmed, volume), music ducked under the voice
  (sidechaincompress), loudness normalized to -14 LUFS (streaming / social standard). Everything that is not the
  voice (music, SFX, clip sound, track clips) is capped below the voice: loudest moment <= voice level - 4 LU,
  peaks <= 60 % of the voice peak, ducked while the voice speaks (spec.mix: cap / bed_ceiling / bed_peak / duck).
- Subtitles: an .srt file from the voice lines and the timeline.
"""

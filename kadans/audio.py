_KREYOL_EXACT_MAP = {
    "nou": "nous",
    "koreksyon": "corréction",
    "nan": "nan",
    "an": "an",
    "bezwen": "besoin",
    "yo": "io",
    "tout": "toute",
    "fèt": "faite",
    "wout": "route",
}


def kreyol_to_phonetic_french(text: str) -> str:
    """Referans fonetik fransè pou kouran sentèz odyo Kreyòl ayisyen (ht) sèlman.
    Tèks afichaj, sou-tit ak .words.json konsève òtograf kreyòl orijinal la."""
    if not text:
        return ""
    try:
        from wasdev.app.ai.kreyol_phonetics import kreyol_to_phonetic_french as _wasdev_k2f
        return _wasdev_k2f(text)
    except Exception:
        pass
    out = re.sub(r"\bkounye\s+a\b", lambda m: "Kounyeya" if m.group(0)[0].isupper() else "kounyeya", str(text), flags=re.IGNORECASE)

    def _word(m: re.Match) -> str:
        w = m.group(0)
        low = w.lower()
        if low in _KREYOL_EXACT_MAP:
            rep = _KREYOL_EXACT_MAP[low]
            return rep.capitalize() if w[0].isupper() else rep
        if len(low) > 4 and low.endswith("syon"):
            rep = w[:-4] + ("TION" if w[-4:].isupper() else "tion")
            return rep
        if len(low) > 2 and low.endswith("e") and low not in ("se", "ke", "le", "de", "ne", "me", "te", "ce", "je"):
            return w + ("R" if w[-1].isupper() else "r")
        return w

    return re.sub(r"\b[^\W\d_]+\b", _word, out, flags=re.UNICODE)


def elevenlabs_synthesize(text: str, out_wav: Path, lang: str = "fr", gender: str = "female",
                          voice_id: str | None = None, api_key: str | None = None, model_id: str | None = None) -> bool:
    import urllib.request
    cfg = load_kadans_settings()
    key = (api_key or cfg.get("elevenlabs_api_key") or "").strip()
    if not key:
        return False
    vid = (voice_id or "").strip()
    if not vid or not re.fullmatch(r"[A-Za-z0-9]{10,40}", vid):
        vid = cfg.get("elevenlabs_voice_male") if gender == "male" else cfg.get("elevenlabs_voice_female")
        vid = vid or ("pNInz6obpgDQGcFmaJgB" if gender == "male" else "21m00Tcm4TlvDq8ikWAM")
    mdl = (model_id or cfg.get("elevenlabs_model") or "eleven_multilingual_v2").strip()
    url = f"https://api.elevenlabs.io/v1/text-to-speech/{vid}"
    lang_code = (lang or "fr").split("-")[0].lower().strip()
    synth_text = kreyol_to_phonetic_french(text) if lang_code == "ht" else text
    payload = json.dumps({
        "text": synth_text,
        "model_id": mdl,
        "voice_settings": {"stability": 0.38, "similarity_boost": 0.78, "style": 0.40, "use_speaker_boost": True},
    }).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=payload,
        headers={
            "xi-api-key": key,
            "Content-Type": "application/json",
            "Accept": "audio/mpeg",
        },
        method="POST",
    )
    tmp_mp3 = out_wav.with_suffix(".eleven.mp3")
    try:
        with urllib.request.urlopen(req, timeout=45) as resp:
            audio_bytes = resp.read()
        if not audio_bytes or len(audio_bytes) < 200:
            return False
        out_wav.parent.mkdir(parents=True, exist_ok=True)
        tmp_mp3.write_bytes(audio_bytes)
        # Micro-fondu adousi (25ms attack / 35ms decay) pou evite klik ak koupe souf nan kòmansman ak finisman
        af_smooth = "afade=t=in:ss=0:d=0.025,areverse,afade=t=in:ss=0:d=0.035,areverse"
        _run([find_tool("ffmpeg"), "-y", "-v", "error", "-i", str(tmp_mp3), "-af", af_smooth, "-ar", str(SR), "-ac", "2",
              "-c:a", "pcm_s16le", str(out_wav)], "elevenlabs wav convert")
        return out_wav.is_file() and out_wav.stat().st_size > 1000
    except Exception:
        return False
    finally:
        tmp_mp3.unlink(missing_ok=True)



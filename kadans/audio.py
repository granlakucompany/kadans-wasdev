def _hum_filter(hum) -> str:
    """Filtè notch pou elimine ronfleman sektè elektrik 50Hz (Ewòp) oswa 60Hz (USA/Ayiti)."""
    if not hum:
        return ""
    try:
        hz = int(str(hum).lower().replace("hz", "").strip())
    except (ValueError, TypeError):
        return ""
    if hz in (50, 60):
        return f"notch=f={hz}:p=2,notch=f={hz*2}:p=2,notch=f={hz*3}:p=2"
    return ""


def _denoise_filter(dn) -> str:
    """Filtè adaptatif debritaj FFT (afftdn)."""
    if dn is None or dn is False:
        return "afftdn=nf=-25:nr=12"
    try:
        val = max(1.0, min(30.0, float(dn)))
    except (ValueError, TypeError):
        val = 12.0
    return f"afftdn=nf=-25:nr={val:.1f}"



def _run(cmd: list[str], what: str):
    r = subprocess.run(cmd, capture_output=True, text=True, creationflags=_NOWIN)
    if r.returncode != 0:
        raise MediaError(f"{what}: {r.stderr.strip()[-400:]}")


_FC_FILE_OPT: dict = {}


def _fc(ff: str, graph: str, at: Path) -> list[str]:
    """Agiman filtè a: dirèk si l kout; nan yon fichye si l long (Windows limite liy kòmand lan a 32 767 karaktè -
    yon videyo ak 100+ SFX te depase l). FFmpeg >= 7.1: «-/filter_complex fichye», ansyen yo: -filter_complex_script."""
    if len(graph) < 12000:
        return ["-filter_complex", graph]
    if ff not in _FC_FILE_OPT:
        opt = "-filter_complex_script"
        try:
            v = subprocess.run([ff, "-version"], capture_output=True, text=True, creationflags=_NOWIN).stdout
            m = re.search(r"version n?(\d+)\.(\d+)", v)
            if m and (int(m.group(1)), int(m.group(2))) >= (7, 1):
                opt = "-/filter_complex"
        except OSError:
            pass
        _FC_FILE_OPT[ff] = opt
    at.write_text(graph, encoding="utf-8")
    return [_FC_FILE_OPT[ff], str(at)]


_PEAKS_MEM: dict = {}


def peaks(src, step_ms: int = 10, sr: int = 8000) -> list:
    """Fòm onn ak KACH (memwa + disk, kle = chemen + mtime + gwosè): FFmpeg dekode fichye a YON SÈL FWA,
    pa chak fwa timeline nan redesine (te lanse FFmpeg sou tout fichye a pou chak blòk, chak build)."""
    import hashlib
    import json as _json
    try:
        st = os.stat(src)
    except OSError:
        return []
    key = f"{os.path.abspath(str(src))}|{st.st_mtime_ns}|{st.st_size}|{step_ms}|{sr}"
    hit = _PEAKS_MEM.get(key)
    if hit is not None:
        return hit
    cdir = Path(os.environ.get("LOCALAPPDATA") or Path.home()) / "Kadans" / "peaks"
    cf = cdir / (hashlib.sha1(key.encode("utf-8")).hexdigest()[:20] + ".json")
    try:
        out = _json.loads(cf.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        out = _peaks_raw(src, step_ms, sr)
        if out:
            try:
                cdir.mkdir(parents=True, exist_ok=True)
                cf.write_text(_json.dumps(out, separators=(",", ":")), encoding="utf-8")
            except OSError:
                pass
    if len(_PEAKS_MEM) > 64:
        _PEAKS_MEM.clear()
    _PEAKS_MEM[key] = out
    return out


def _peaks_raw(src, step_ms: int = 10, sr: int = 8000) -> list:
    """Fòm onn: lis valè pik 0..1 chak step_ms (pou editè a desine l san dekode odyo nan navigatè a)."""
    import array
    import subprocess
    try:
        r = subprocess.run([find_tool("ffmpeg"), "-v", "error", "-i", str(src), "-ac", "1",
                            "-ar", str(sr), "-f", "s16le", "-"], capture_output=True)
        data = array.array("h")
        data.frombytes(r.stdout[: len(r.stdout) // 2 * 2])
    except (OSError, ValueError):
        return []
    win = max(1, int(sr * step_ms / 1000))
    out = []
    for i in range(0, len(data), win):
        chunk = data[i:i + win]
        out.append(round(max((abs(x) for x in chunk), default=0) / 32768, 3))
    return out


def wav_seconds(path: Path) -> float:
    try:
        with wave.open(str(path), "rb") as w:
            return w.getnframes() / float(w.getframerate())
    except (wave.Error, EOFError, OSError):
        from .media import probe_audio
        return probe_audio(path)



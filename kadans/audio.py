def music_expr(mood: str, seed: int, total: float) -> str:
    """aevalsrc expression of a generated piece (mono). Seed: key (-3..+3 semitones) and chord order rotation."""
    seg, pulse, prog, octave, loud = MOODS.get(mood, MOODS["upbeat"])
    rnd = random.Random(seed)
    key = 220.0 * 2 ** ((rnd.randint(-3, 3) + octave) / 12)
    rot = rnd.randrange(len(prog))
    prog = prog[rot:] + prog[:rot]
    m = f"mod(t,{seg})"
    env = f"(min(1,{m}/0.25)*(0.55+0.45*exp(-{m}*1.6)))"
    chords = []
    for notes in prog:
        fs = [key * 2 ** (n / 12) for n in notes]
        tones = "+".join(f"sin(2*PI*{f:.3f}*t)+0.25*sin(4*PI*{f:.3f}*t)" for f in fs)
        bass = f"0.9*sin(2*PI*{fs[0] / 2:.3f}*t)"
        chords.append(f"({tones}+{bass})")
    idx = f"mod(floor(t/{seg}),{len(chords)})"
    expr = chords[-1]
    for k in range(len(chords) - 2, -1, -1):
        expr = f"if(eq({idx},{k}),{chords[k]},{expr})"
    beat = f"(0.62+0.38*gt(sin(2*PI*{pulse}*t),0.2))" if pulse else "1"
    return f"{0.045 * loud:.4f}*{env}*{beat}*{expr}"


def music_loop(mood: str, seed: int, cache: Path) -> Path:
    """One full cycle of the generated piece (every chord once; the pulse divides the cycle, so it loops seamlessly),
    rendered once and cached: aevalsrc evaluates every sample, a 40 s ad would otherwise cost ~40 s."""
    seg, _pulse, prog, _o, _l = MOODS.get(mood, MOODS["upbeat"])
    cycle = seg * len(prog)
    cache.mkdir(parents=True, exist_ok=True)
    out = cache / f"music-{mood}-{seed}-v1.wav"
    if not out.is_file():
        tmp = out.with_suffix(".part.wav")
        _run([find_tool("ffmpeg"), "-y", "-v", "error", "-f", "lavfi", "-i",
              f"aevalsrc=exprs='{music_expr(mood, seed, cycle)}':s={SR}:d={cycle:.3f}", "-ac", "2",
              "-c:a", "pcm_s16le", str(tmp)], "music")
        tmp.replace(out)
    return out


def write_srt(spec: dict, tl: list[dict], path: Path, max_chars: int = 42) -> Path | None:
    """Subtitles from the voice lines: each line split in readable pieces, timed in proportion to their words."""
    rows = []
    for sc, t in zip(spec["scenes"], tl):
        text = re.sub(r"\*+", "", sc.get("voice") or " ".join(w["w"] for w in t.get("words") or [])).strip()
        if not text or not t.get("voice_dur"):
            continue
        if t.get("words"):                                   # real word times: each piece starts on its first word
            ws, n = t["words"], max(1, -(-len(text) // max_chars))
            target, cur = len(text) / n, []
            for w in ws:
                cur.append(w)
                if len(" ".join(x["w"] for x in cur)) >= target and w is not ws[-1]:
                    rows.append((cur[0]["s"], cur[-1]["e"] + 0.15, " ".join(re.sub(r"\*+", "", x["w"]) for x in cur)))
                    cur = []
            if cur:   # *mo* an koulè: retire TOUT «*» (strip pa t wè «*chiffres*,» ak «l'*IA*.»)
                rows.append((cur[0]["s"], cur[-1]["e"] + 0.15, " ".join(re.sub(r"\*+", "", x["w"]) for x in cur)))
            continue
        words = text.split()
        n = max(1, -(-len(text) // max_chars))              # pieces of about the same length (no lonely word)
        pieces, cur, target = [], [], len(text) / n
        for w in words:
            cur.append(w)
            if len(" ".join(cur)) >= target and len(pieces) < n - 1:
                pieces.append(" ".join(cur))
                cur = []
        if cur:
            pieces.append(" ".join(cur))
        total_w = sum(len(p.split()) for p in pieces) or 1
        at = t["voice_at"]
        for p in pieces:
            d = t["voice_dur"] * len(p.split()) / total_w
            rows.append((at, at + d, p))
            at += d
    if not rows:
        return None
    rows = [(a, min(b, rows[i + 1][0] - 0.02) if i + 1 < len(rows) else b, txt)       # never overlap the next one
            for i, (a, b, txt) in enumerate(rows)]

    def ts(x: float) -> str:
        ms = int(round(x * 1000))
        return f"{ms // 3600000:02d}:{ms // 60000 % 60:02d}:{ms // 1000 % 60:02d},{ms % 1000:03d}"
    path.write_text("\n".join(f"{i + 1}\n{ts(a)} --> {ts(b)}\n{txt}\n" for i, (a, b, txt) in enumerate(rows)),
                    encoding="utf-8")
    return path



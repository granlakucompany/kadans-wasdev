def check_render(spec: dict, tl: list, mp4: Path, lang: str = "fr") -> dict:
    """KONTWÒL APRE RANN: Whisper (ak lè mo) sou MP4 final la → chak fraz tonbe nan bon sèn + vwa pa koupe.
    {checked, ok, issues:[{scene,id,kind:voice_wrong_scene|voice_cut,...}]}. faster-whisper opsyonèl."""
    try:
        from faster_whisper import WhisperModel
    except Exception:                                    # noqa: BLE001
        return {"checked": False, "note": "faster-whisper pa enstale (kontwòl MP4 sote)", "issues": []}
    import difflib
    try:
        model = WhisperModel("small", device="cpu", compute_type="int8")
        lex = (spec.get("voice") or {}).get("lexicon") or {}        # mo mak yo bay Whisper davans
        brand = (spec.get("brand") or {}).get("name") or ""
        words = [str(w) for w in (lex.get(lang, lex) if isinstance(lex, dict) else {})]
        prompt = ", ".join(([brand] if brand else []) + words[:40]) or None
        segs, _info = model.transcribe(str(mp4), language=("fr" if lang == "ht" else (lang if lang in ("fr", "en", "es", "pt", "de", "it", "ru") else None)),
                                       word_timestamps=True, initial_prompt=prompt)
        words = [(w.word, float(w.start), float(w.end)) for s in segs for w in (s.words or [])]
    except Exception as e:                               # noqa: BLE001
        return {"checked": False, "note": f"Whisper pa t travay: {e}", "issues": []}
    issues = []
    for i, (sc, t) in enumerate(zip(spec["scenes"], tl)):
        if not sc.get("voice"):
            continue
        s0, s1 = t["start"], t["start"] + t["dur"]
        heard = [w for w in words if s0 <= (w[1] + w[2]) / 2 < s1]
        want = " ".join(_n(x) for x in re.sub(r"\*+", "", sc["voice"]).split() if _n(x))
        got = " ".join(_n(w[0]) for w in heard if _n(w[0]))      # konparezon PA KARAKTÈ (pi endiljan: Whisper
        ratio = difflib.SequenceMatcher(None, got, want).ratio() if want else 1.0   # tande franse a mal souvan)
        last_end = max((w[2] for w in heard), default=s0)
        margin = s1 - last_end
        if want and ratio < 0.55:
            issues.append({"scene": i, "id": sc["id"], "kind": "voice_wrong_scene", "ratio": round(ratio, 2),
                           "heard": " ".join(w[0].strip() for w in heard)[:80]})
        elif heard and margin < 0.08:
            issues.append({"scene": i, "id": sc["id"], "kind": "voice_cut", "margin_s": round(margin, 2)})
    return {"checked": True, "ok": not issues, "issues": issues}


def _n(w: str) -> str:
    w = unicodedata.normalize("NFD", str(w).lower())
    return "".join(c for c in w if c.isalnum() and unicodedata.category(c) != "Mn")


def align_script(script: str, heard: list, dur: float) -> list[list]:
    """Put the SCRIPT words (right spelling: «Wasdev», not «Vasdev») on the times a speech recognizer heard.
    heard = [[word, start, end], ...]. Words it missed get times interpolated between their neighbours."""
    from .spec import estimate_words
    toks = script.split()
    if not heard:
        return estimate_words(script, dur)
    a, b = [_n(t) for t in toks], [_n(h[0]) for h in heard]
    times: list = [None] * len(toks)
    for blk in difflib.SequenceMatcher(None, a, b, autojunk=False).get_matching_blocks():
        for k in range(blk.size):
            times[blk.a + k] = (heard[blk.b + k][1], heard[blk.b + k][2])
    for op, i1, i2, j1, j2 in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if op == "replace" and i2 - i1 == j2 - j1:                       # same count, other spelling: take them
            for k in range(i2 - i1):
                times[i1 + k] = (heard[j1 + k][1], heard[j1 + k][2])
    n, i = len(toks), 0
    while i < n:                                                          # runs of missed words: share the gap
        if times[i] is not None:
            i += 1
            continue
        j = i
        while j < n and times[j] is None:
            j += 1
        prev = times[i - 1][1] if i > 0 else 0.0
        nxt = times[j][0] if j < n else dur
        span = max(0.05, (nxt - prev) / (j - i))
        for q in range(i, j):
            times[q] = (prev + span * (q - i), prev + span * (q - i + 0.9))
        i = j
    return [[t, round(s0, 3), round(max(s0 + 0.05, e0), 3)] for t, (s0, e0) in zip(toks, times)]


def voice_files(spec: dict, base: Path | None) -> dict:
    """{scene id: WAV} pou sèn ki gen yon voice_file (vwa pre-anrejistre / pre-jenere). Aperçu a (composition +
    Timeline) itilize yo menm jan ak rann lan: VRÈ dire vwa a ak lè mo yo (<wav>.words.json), pa yon estimasyon tèks."""
    out = {}
    for sc in spec.get("scenes") or []:
        vf = sc.get("voice_file")
        if not vf:
            continue
        try:
            p = Path(resolve(vf, base))
            if not p.is_file() and base is not None:
                vf_name = Path(vf).name
                found = list(Path(base).glob(f"**/{vf_name}"))
                if found and found[0].is_file():
                    p = found[0].resolve()
        except Exception:                                        # noqa: BLE001
            continue
        if p.is_file() and p.suffix.lower() == ".wav":
            sp = scene_voice_speed(spec, sc)
            if abs(sp - 1.0) > 1e-3:
                try:
                    p = speed_wav(p, sp)
                except Exception:                                # noqa: BLE001 — ffmpeg manke: vitès nòmal
                    pass
            out[sc["id"]] = str(p)
    return out


def word_times(spec: dict, vmap: dict, cache: Path, align=None) -> dict:
    """{scene id: [[word, start, end], ...]} for every voice line. align(wav, text, lang) -> heard words (e.g.
    Whisper); cached next to the voice WAV. Without align (or if it fails): estimated from the WAV length."""
    from .spec import estimate_words
    out = {}
    lang = (spec.get("voice") or {}).get("lang") or spec.get("lang")
    for sc in spec["scenes"]:
        wav = vmap.get(sc["id"])
        if not wav or not (sc.get("voice") or sc.get("voice_file")):
            continue
        dur = wav_seconds(Path(wav))
        # «voice-x.wav.words.json» (ElevenLabs / whisper_align WASDEV) OSWA «voice-x.words.json»: anvan sèl dezyèm
        # non an te li → aperçu Timeline (san align) te estime lè mo yo pandan rann lan te gen vrè lè yo
        js = next((c for c in (Path(str(wav) + ".words.json"), Path(wav).with_suffix(".words.json")) if c.is_file()),
                  Path(wav).with_suffix(".words.json"))
        heard = None
        if js.is_file():
            try:
                heard = json.loads(js.read_text(encoding="utf-8"))
            except ValueError:
                heard = None
        if heard is None and align is not None:
            try:
                heard = [[str(w), float(a), float(b)] for w, a, b in align(Path(wav), sc.get("voice") or "", lang)]
                js.write_text(json.dumps(heard, ensure_ascii=False), encoding="utf-8")
            except Exception:                                    # noqa: BLE001 - recognizer missing: estimate
                heard = None
        if not sc.get("voice"):                     # voice-over without its text: the words Whisper heard
            out[sc["id"]] = heard or []
        else:
            out[sc["id"]] = align_script(sc["voice"], heard, dur) if heard else estimate_words(sc["voice"], dur)
    return out



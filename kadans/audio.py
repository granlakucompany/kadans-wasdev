MIX_DEFAULTS = {"cap": True, "bed_ceiling": -4.0, "bed_peak": 0.6, "duck": True, "fx_peak": 0.9, "fx_duck": True,
                "target_lufs": -14.0, "target_tp": -1.5, "hum_hz": None, "clarity_preset": "podcast", "denoise": 12}

def bed_cap(spec: dict) -> dict | None:
    """Reglaj plafon an (spec.mix: cap / bed_ceiling LU / bed_peak 0.1-1 / duck) - None si cap=false."""
    m = spec.get("mix") if isinstance(spec.get("mix"), dict) else {}
    if m.get("cap", True) is False:
        return None
    def num(k, lo, hi):
        try:
            return max(lo, min(hi, float(m.get(k, MIX_DEFAULTS[k]))))
        except (TypeError, ValueError):
            return MIX_DEFAULTS[k]
    return {"ceiling": num("bed_ceiling", -40.0, 0.0), "peak": num("bed_peak", 0.1, 1.0),
            "duck": m.get("duck", True) is not False, "fx_peak": num("fx_peak", 0.1, 1.0),
            "fx_duck": m.get("fx_duck", True) is not False}


def _loudness(ff: str, wav: Path) -> tuple[float, float, float]:
    """(I entegre LUFS, maksimòm momantane LUFS, pik echantiyon lineyè) yon WAV - filtè ebur128 FFmpeg."""
    r = subprocess.run([ff, "-hide_banner", "-nostats", "-i", str(wav), "-af", "ebur128=peak=sample:framelog=info",
                        "-f", "null", "-"], capture_output=True, text=True, errors="replace", creationflags=_NOWIN)
    err = r.stderr or ""
    ms = [float(x) for x in re.findall(r"\bM:\s*(-?\d+(?:\.\d+)?)", err)]
    ii = re.findall(r"\bI:\s*(-?\d+(?:\.\d+)?) LUFS", err)
    pk = re.findall(r"Peak:\s*(-?\d+(?:\.\d+)?|-inf) dBFS", err)
    return (float(ii[-1]) if ii else -70.0, max(ms) if ms else -120.0,
            10 ** (float(pk[-1]) / 20) if pk and pk[-1] != "-inf" else 0.0)


def _lim(target: float) -> tuple[float, float]:
    """alimiter pa aksepte limit < 0.0625: limite a 0.0625 epi bese apre."""
    return (target, 1.0) if target >= 0.0625 else (0.0625, target / 0.0625)


def _mix_capped(ff, inputs, chains, voice_labels, bed, base_label, total, mvol, raw, cap, fx=None):
    """Mix an 2 pas: (1) vwa a, lit la ak bis SFX la ekri apa epi mezire; (2) lit la bese anba vwa a, limite, duck;
    SFX yo limite anba pik vwa a ak yon ti duck lejè; tout melanje."""
    fx = list(fx or [])
    if not bed:                                                         # sèlman SFX: lit vid (silans)
        bed = []
    vwav, bwav, fwav = raw.with_suffix(".voice.wav"), raw.with_suffix(".bed.wav"), raw.with_suffix(".fx.wav")
    pre = list(chains) + [
        f"{base_label}asplit=3[nb1][nb2][nb3]",
        f"{''.join(voice_labels)}[nb1]amix=inputs={len(voice_labels) + 1}:normalize=0:duration=longest,atrim=0:{total:.3f}[vbus]",
        f"{''.join(bed)}[nb2]amix=inputs={len(bed) + 1}:normalize=0:duration=longest,atrim=0:{total:.3f}[bbus]",
        f"{''.join(fx)}[nb3]amix=inputs={len(fx) + 1}:normalize=0:duration=longest,atrim=0:{total:.3f}[fbus]"]
    fcf = raw.with_suffix(".fc.txt")
    _run([ff, "-y", "-v", "error", *inputs, *_fc(ff, ";".join(pre), fcf),
          "-map", "[vbus]", "-c:a", "pcm_s16le", "-t", f"{total:.3f}", str(vwav),
          "-map", "[bbus]", "-c:a", "pcm_s16le", "-t", f"{total:.3f}", str(bwav),
          "-map", "[fbus]", "-c:a", "pcm_s16le", "-t", f"{total:.3f}", str(fwav)], "sound stems")
    fcf.unlink(missing_ok=True)
    v_i, v_m, v_pk = _loudness(ff, vwav)
    b_i, b_m, b_pk = _loudness(ff, bwav)
    gain = 1.0
    if v_i > -70 and b_m > -70:                                         # sèlman BESE lit la, pa janm monte l
        gain = min(1.0, 10 ** ((v_i + cap["ceiling"] - b_m) / 20))
    target = max(0.005, min(1.0, (v_pk or 1.0) * cap["peak"]))
    lim, post = _lim(target)
    fx_target = max(0.005, min(1.0, (v_pk or 1.0) * cap.get("fx_peak", 0.9)))
    flim, fpost = _lim(fx_target)
    keep = _os.environ.get("KADANS_KEEP_STEMS") == "1"
    ch = [f"[1:a]volume={gain:.5f},alimiter=limit={lim:.5f}:level=0:attack=5:release=60,volume={post:.5f}[bcap]",
          f"[2:a]alimiter=limit={flim:.5f}:level=0:attack=1:release=50,volume={fpost:.5f}[fcap]"]
    nsc = (1 if cap["duck"] else 0) + (1 if cap.get("fx_duck", True) else 0)
    if nsc:
        ch.append(f"[0:a]asplit={nsc + 1}[vb]" + "".join(f"[vsc{i}]" for i in range(nsc)))
        vlab, si = "[vb]", 0
    else:
        vlab, si = "[0:a]", 0
    if cap["duck"]:
        ch.append(f"[bcap][vsc{si}]sidechaincompress=threshold=0.02:ratio=9:attack=15:release=380[bduck]")
        si += 1
    else:
        ch.append("[bcap]anull[bduck]")
    if cap.get("fx_duck", True):                                        # SFX: ti duck lejè, son an rete tande
        ch.append(f"[fcap][vsc{si}]sidechaincompress=threshold=0.06:ratio=2.5:attack=5:release=200[fduck]")
    else:
        ch.append("[fcap]anull[fduck]")
    blab = "[bduck]"
    if keep:
        ch.append("[bduck]asplit=2[bd1][bd2]")
        blab = "[bd1]"
    ch.append(f"{vlab}{blab}[fduck]amix=inputs=3:normalize=0:duration=longest,atrim=0:{total:.3f},volume={mvol:.3f}[out]")
    outs = ["-map", "[out]", "-c:a", "pcm_s16le", "-t", f"{total:.3f}", str(raw)]
    if keep:
        outs += ["-map", "[bd2]", "-c:a", "pcm_s16le", "-t", f"{total:.3f}", str(raw.with_suffix(".bedfinal.wav"))]
    _run([ff, "-y", "-v", "error", "-i", str(vwav), "-i", str(bwav), "-i", str(fwav), "-filter_complex", ";".join(ch), *outs],
         "sound mix")
    LAST_MIX.clear()
    LAST_MIX.update({"voice_I": v_i, "voice_M_max": v_m, "voice_peak": round(v_pk, 4), "bed_I": b_i,
                     "bed_M_max": b_m, "bed_gain_db": round(20 * math.log10(max(gain, 1e-6)), 2),
                     "bed_limit": round(target, 4), "fx_limit": round(fx_target, 4), "fx_clips": len(fx), **cap})
    if keep:
        Path(str(raw.with_suffix("")) + ".mix.json").write_text(json.dumps(LAST_MIX, indent=1), encoding="utf-8")
    else:
        vwav.unlink(missing_ok=True)
        bwav.unlink(missing_ok=True)
        fwav.unlink(missing_ok=True)


# RÈG OBLIGATWA: VWA YO PA JANM KOUPE (devlopè a, 2026-10-20). Avan vwa a: PRE_MS silans (debrwiyè afftdn /
# konpresè a «chofe» sou silans — premye son an pa manje), apre l: POST_S silans (dènye son an fini nèt). Vwa a
# rete EGZAKTEMAN nan menm plas la sou timeline la (adelay final la retire PRE_MS la).
PRE_MS, POST_S = 150, 0.35


def _voice_pad(ms: int) -> str:
    pre = min(PRE_MS, max(0, ms))
    return (f",adelay={pre}|{pre}" if pre else "") + f",apad=pad_dur={POST_S}"


def _voice_place(ms: int) -> str:
    pre = min(PRE_MS, max(0, ms))
    return f",adelay={ms - pre}|{ms - pre}"


VOICE_RX = re.compile(r"\b(voice|voix|vwa|narra\w*|vo|dyal[oò]g\w*|dialog\w*|speech|replik\w*)\b")
VOICE_PATH_RX = re.compile(r"[\\/](vwa|voice|voix)[\\/]")


def is_voice_clip(track: dict, clip: dict, path) -> bool:
    """Klip track ki se yon VWA (naratè / dyalòg): li pa janm koupe, pa gen fondi long nan kòmansman."""
    if clip.get("voice") is True:
        return True
    txt = " ".join(str(x or "") for x in (track.get("kind"), track.get("name"), clip.get("kind"), clip.get("name")))
    return bool(VOICE_RX.search(txt.lower())) or bool(VOICE_PATH_RX.search(str(path).lower()))


def mix(spec: dict, tl: list[dict], total: float, out: Path, base: Path | None = None, vmap: dict | None = None,
        cache: Path | None = None, cues: list | None = None) -> Path:
    """Final soundtrack (AAC in .m4a): voices + clip sound + (ducked) music, -14 LUFS, exactly `total` seconds."""
    ff = find_tool("ffmpeg")
    inputs, chains, voice_labels, other_labels = [], [], [], []
    fmt = f"aformat=sample_rates={SR}:channel_layouts=stereo"
    by_id = {t["id"]: t for t in tl}
    # Koleksyon klip vwa ki sou track yo pou evite 2 vwa youn sou lòt (anti-collision)
    track_voice_spans = []
    for tk in (spec.get("tracks") or []):
        if tk.get("muted"):
            continue
        for c in (tk.get("clips") or []):
            cp = resolve(c.get("src", ""), base) if c.get("src") else None
            if is_voice_clip(tk, c, cp):
                c_st = float(c.get("start", 0) or 0)
                c_dur = float(c.get("dur", 2) or 2)
                track_voice_spans.append((c_st, c_st + c_dur))

    for sc in spec["scenes"]:
        t = by_id[sc["id"]]
        sc_st = float(t.get("start", 0))
        sc_dur = float(t.get("dur", 2))
        sc_end = sc_st + sc_dur
        # Si gen yon klip vwa sou yon track ki kouvri sèn sa a, pa double vwa sèn nan
        voice_collision = any(vst < sc_end - 0.2 and vend > sc_st + 0.2 for vst, vend in track_voice_spans)

        p = (vmap or {}).get(sc["id"])
        v_offset = float(sc.get("voice_offset", 0.0) or 0.0)
        if p and not voice_collision:
            k = sum(a == "-i" for a in inputs)
            inputs += ["-i", str(p)]
            ms = max(0, int(round((t["voice_at"] + v_offset) * 1000)))
            vclean = f",{voice_fx(spec)}" if (spec.get("voice") or {}).get("enhance", True) else ""
            chains.append(f"[{k}:a]{fmt}{_voice_pad(ms)}{vclean}{_voice_place(ms)}[v{k}]")
            voice_labels.append(f"[v{k}]")
        elif sc.get("voice_file") and not voice_collision:
            vf = resolve(sc["voice_file"], base)
            if vf and Path(vf).is_file():
                k = sum(a == "-i" for a in inputs)
                inputs += ["-i", str(vf)]
                ms = max(0, int(round((t["start"] + v_offset) * 1000)))
                vclean = f",{voice_fx(spec)}" if (spec.get("voice") or {}).get("enhance", True) else ""
                chains.append(f"[{k}:a]{fmt}{_voice_pad(ms)}{vclean}{_voice_place(ms)}[v{k}]")
                voice_labels.append(f"[v{k}]")
        if sc["type"] == "video":
            vol = sc.get("audio")
            if vol is None:
                vol = 0.0 if (vmap and (sc.get("voice") or sc.get("voice_file"))) else 0.8
            if vol > 0:
                src = resolve(sc["src"], base)
                length = t.get("clip") or t["dur"]
                vsp = float(sc.get("speed") or 1.0)          # VITÈS klip la: sekonn SOUS = sekonn timeline × vitès
                k = sum(a == "-i" for a in inputs)
                inputs += ["-ss", f"{sc.get('in', 0.0):.3f}", "-t", f"{min(length, t['dur']) * vsp:.3f}", "-i", str(src)]
                ms = int(round(t["start"] * 1000))
                fade = max(0.0, min(length, t["dur"]) - 0.3)
                tempo = atempo(vsp)
                chains.append(f"[{k}:a]{fmt}{',' + tempo if tempo else ''},volume={vol:.3f},afade=t=out:st={fade:.3f}:d=0.3,"
                              f"adelay={ms}|{ms}[c{k}]")
                other_labels.append(f"[c{k}]")
    fx_labels = []                                                      # bis SFX (v2.78): pa kraze anba duck mizik la
    tk_clips: dict = {}                                                 # fichye -> [(chèn filtè, se SFX?)]
    _has_solo = any(t.get("solo") for t in (spec.get("tracks") or []) if isinstance(t, dict))   # solo (T4)
    for tk in (spec.get("tracks") or []):                              # clip odyo/video sou track yo (rekòd + medya enpòte)
        if tk.get("muted") or (_has_solo and not tk.get("solo")):      # gen solo: sèlman track solo yo nan mix la
            continue
        tk_fx = str(tk.get("kind") or "").lower() == "sfx" or str(tk.get("name") or "").lower().startswith("sfx")
        for c in (tk.get("clips") or []):
            if c.get("kind") == "sfx" and c.get("sfx") in SFX:          # klip panèl SFX Kadans Timeline la
                tsrc = sfx_file(c["sfx"], cache or out.parent)
                c = dict(c, volume=c.get("volume", SFX_LEVEL.get(c["sfx"], 0.3) * 2))
            elif (c.get("kind") not in ("audio", "video")) or not c.get("src"):
                continue
            else:
                tsrc = resolve(c["src"], base)
            if not tsrc or not Path(tsrc).is_file():
                continue
            is_fx = tk_fx or c.get("kind") == "sfx"
            try:
                vol = float(c.get("volume", 1)); start = float(c.get("start", 0)); dur = float(c.get("dur", 2))
                fin = float(c.get("fadein", 0)); fout = float(c.get("fadeout", 0))
            except (TypeError, ValueError):
                continue
            if vol <= 0 or dur <= 0:
                continue
            from .compose import clip_speed
            csp = clip_speed(c)
            try:
                c_in = max(0.0, float(c.get("in", 0) or 0))       # KOUPE nan timeline la: kote klip la kòmanse nan fichye a
            except (TypeError, ValueError):
                c_in = 0.0
            if not is_fx and is_voice_clip(tk, c, tsrc):
                # RÈG OBLIGATWA: yon klip VWA pa janm koupe (dur twò kout → tout vwa a) ni fonn nan kòmansman an
                try:
                    full = wav_seconds(Path(tsrc)) if str(tsrc).lower().endswith(".wav") else 0.0
                except Exception:                                # noqa: BLE001
                    full = 0.0
                if full > 0 and not c.get("in") and not c.get("out"):   # klip ENTYE (pa koupe nan timeline la)
                    dur = max(dur, full / csp + 0.05)
                fin, fout = min(fin, 0.02), min(fout, 0.05)
            ms = int(round(start * 1000))
            tempo = atempo(csp)                              # VITÈS klip la (son an swiv, ton an pa chanje)
            tail = (f"{fmt},atrim={c_in:.3f}:{c_in + dur * csp:.3f},asetpts=PTS-STARTPTS{',' + tempo if tempo else ''},"
                    f"volume={vol:.3f}")
            if fin > 0:
                tail += f",afade=t=in:st=0:d={min(fin, dur):.3f}"
            if fout > 0:
                tail += f",afade=t=out:st={max(0.0, dur - fout):.3f}:d={min(fout, dur):.3f}"
            # 3yèm valè = SEKONN FICHYE pou dekode (in + dur × vitès): avan se te «dur» → yon klip koupe (in > 0)
            # te dekode sèlman dur premye segonn yo epi atrim nan pa t jwenn anyen (son vid)
            # «aresample async» apre adelay: ak FFmpeg 8.1, yon klip KOUPE (atrim ki pa kòmanse nan 0) + amix te PÈDI
            # silans adelay la → klip la te tonbe nan KÒMANSMAN videyo a («son an tounen nan plas li», 2026-10-20)
            tk_clips.setdefault(str(tsrc), []).append((f"{tail},adelay={ms}|{ms},aresample=async=1:first_pts=0", is_fx, c_in + dur * csp, False))
    from .sounds import clips as _sound_clips                          # son sèn yo (sounds / ambience) + pa pèsonaj yo
    for c in _sound_clips(spec, tl, base, total)[0]:
        ms = int(round(c["start"] * 1000))
        tail = f"{fmt},atrim=0:{c['dur']:.3f},asetpts=PTS-STARTPTS,volume={c['volume']:.3f}"
        if c["fadein"] > 0:
            tail += f",afade=t=in:st=0:d={c['fadein']:.3f}"
        if c["fadeout"] > 0:
            tail += f",afade=t=out:st={max(0.0, c['dur'] - c['fadeout']):.3f}:d={c['fadeout']:.3f}"
        tk_clips.setdefault(str(c["path"]), []).append((f"{tail},adelay={ms}|{ms},aresample=async=1:first_pts=0", c["fx"], c["dur"], c["loop"]))
    # YON SÈL antre pa fichye (asplit pou chak fwa li repete): 100+ klip SFX pa fè liy kòmand lan depase limit Windows
    for tsrc, uses in tk_clips.items():
        k = sum(a == "-i" for a in inputs)
        if any(u[3] for u in uses):                                     # ambyans an bouk (fichye a pi kout pase sèn nan)
            inputs += ["-stream_loop", "-1"]
        inputs += ["-t", f"{max(u[2] for u in uses):.3f}", "-i", tsrc]    # pa dekode plis pase klip ki pi long lan
        srcs = [f"[s{k}_{j}]" for j in range(len(uses))] if len(uses) > 1 else [f"[{k}:a]"]
        if len(uses) > 1:
            chains.append(f"[{k}:a]asplit={len(uses)}{''.join(srcs)}")
        for j, (tail, is_fx, _d, _lp) in enumerate(uses):
            chains.append(f"{srcs[j]}{tail}[tk{k}_{j}]")
            (fx_labels if is_fx else other_labels).append(f"[tk{k}_{j}]")
    music = spec.get("music")
    mus = None
    if music:
        k = sum(a == "-i" for a in inputs)
        if music.get("file"):
            inputs += ["-stream_loop", "-1", "-i", str(resolve(music["file"], base))]
        else:
            loop = music_loop(music["mood"], music.get("seed", 0), cache or out.parent)
            inputs += ["-stream_loop", "-1", "-i", str(loop)]
        fade_out = max(0.0, total - 2.0)
        chains.append(f"[{k}:a]{fmt},atrim=0:{total:.3f},afade=t=in:d=1.2,afade=t=out:st={fade_out:.3f}:d=2,"
                      f"volume={music['volume'] / 0.22 * 0.55:.3f}[mus]")
        mus = "[mus]"
    fx = spec.get("sfx")
    if fx and cues and fx["volume"] > 0:                                # sound effects on their cues
        for kind in ("whoosh", "pop", "hit", "type", "text"):
            times = [c["t"] for c in cues if c["kind"] == kind and c["t"] < total - 0.1]
            if not times:
                continue
            k = sum(a == "-i" for a in inputs)
            inputs += ["-i", str(sfx_file(kind, cache or out.parent))]
            lv = SFX_LEVEL[kind] * fx["volume"] * 2
            labels = [f"[x{k}_{j}]" for j in range(len(times))]
            chains.append(f"[{k}:a]{fmt},volume={lv:.3f},asplit={len(times)}{''.join(labels)}" if len(times) > 1
                          else f"[{k}:a]{fmt},volume={lv:.3f}{labels[0]}")
            for j, tt in enumerate(times):
                ms = int(round(tt * 1000))
                chains.append(f"{labels[j]}adelay={ms}|{ms}[y{k}_{j}]")
                fx_labels.append(f"[y{k}_{j}]")
    k = sum(a == "-i" for a in inputs)
    inputs += ["-f", "lavfi", "-i", f"anullsrc=r={SR}:cl=stereo:d={total:.3f}"]        # length + never silent-empty
    base_label = f"[{k}:a]"
    mvol = max(0.0, min(2.0, float(spec.get("volume", 1) or 1)))
    bed = ([mus] if mus else []) + other_labels
    out.parent.mkdir(parents=True, exist_ok=True)
    raw = out.with_suffix(".raw.wav")
    cap = bed_cap(spec)
    mx_cfg = spec.get("mix") if isinstance(spec.get("mix"), dict) else {}
    if voice_labels and (bed or fx_labels) and cap:
        _mix_capped(ff, inputs, chains, voice_labels, bed, base_label, total, mvol, raw, cap, fx_labels)
    else:
        LAST_MIX.clear()
        if voice_labels:
            chains.append(f"{''.join(voice_labels)}amix=inputs={len(voice_labels)}:normalize=0:duration=longest[vbus]")
            if mus:
                chains.append("[vbus]asplit=2[vb][vsc]")
                chains.append(f"{mus}[vsc]sidechaincompress=threshold=0.02:ratio=9:attack=15:release=380[mduck]")
                parts = ["[vb]", "[mduck]"]
            else:
                parts = ["[vbus]"]
        else:
            parts = [mus] if mus else []
        parts += other_labels + fx_labels + [base_label]
        chains.append(f"{''.join(parts)}amix=inputs={len(parts)}:normalize=0:duration=longest,atrim=0:{total:.3f},volume={mvol:.3f}[out]")
        fcf = raw.with_suffix(".fc.txt")
        _run([ff, "-y", "-v", "error", *inputs, *_fc(ff, ";".join(chains), fcf), "-map", "[out]",
              "-c:a", "pcm_s16le", "-t", f"{total:.3f}", str(raw)], "sound mix")
        fcf.unlink(missing_ok=True)
    try:
        target_lufs = max(-70.0, min(-5.0, float(mx_cfg.get("target_lufs", -14.0))))
    except (TypeError, ValueError):
        target_lufs = -14.0
    try:
        target_tp = max(-20.0, min(0.0, float(mx_cfg.get("target_tp", -1.5))))
    except (TypeError, ValueError):
        target_tp = -1.5
    # loudness in two passes: measure, then a linear gain to target LUFS (one pass drifts by ~1 LU)
    r = subprocess.run([ff, "-hide_banner", "-nostats", "-i", str(raw), "-af",
                        f"loudnorm=I={target_lufs:.1f}:TP={target_tp:.1f}:LRA=11:print_format=json", "-f", "null", "-"],
                       capture_output=True, text=True, creationflags=_NOWIN)
    try:
        m = json.loads(r.stderr[r.stderr.rindex("{"):r.stderr.rindex("}") + 1])
        if not float(m["input_i"]) > -70:                       # silence (no voice, no music): nothing to level
            raise ValueError("silent")
        ln = (f"loudnorm=I={target_lufs:.1f}:TP={target_tp:.1f}:LRA=11:measured_I={m['input_i']}:measured_TP={m['input_tp']}:"
              f"measured_LRA={m['input_lra']}:measured_thresh={m['input_thresh']}:offset={m['target_offset']}:linear=true")
    except (ValueError, KeyError) as e:
        ln = "anull" if str(e) == "silent" or "inf" in r.stderr[-400:] else f"loudnorm=I={target_lufs:.1f}:TP={target_tp:.1f}:LRA=11" 
    codec_args = ["-c:a", "pcm_s16le"] if out.suffix.lower() == ".wav" else ["-c:a", "aac", "-b:a", "192k"]
    _run([ff, "-y", "-v", "error", "-i", str(raw), "-af", f"{ln},aresample={SR}", *codec_args,
          "-t", f"{total:.3f}", str(out)], "loudness")
    raw.unlink(missing_ok=True)
    return out


def preview_sounds(spec: dict, tl: list[dict], folder: Path, base: Path | None = None,
                   cache: Path | None = None) -> Path | None:
    """APERÇU: son sèn yo SAN vwa (ambyans, sounds, pa pèsonaj yo, mizik, SFX otomatik, klip odyo) →
    <folder>/preview-sounds.m4a pou composition.html jwe l (pa depanse kredi vwa). None = pa gen anyen pou jwe."""
    has = (spec.get("music") or spec.get("sfx") or any(sc.get("sounds") or sc.get("ambience") for sc in spec["scenes"])
           or any(a.get("steps") for t in tl for ch in (t.get("rig") or {}).values() for a in ch["do"])
           or any(c.get("kind") in ("audio", "sfx") for tk in spec.get("tracks") or [] for c in tk.get("clips") or []))
    if not has or not tl:
        return None
    from .compose import events
    from .spec import total
    out = Path(folder) / "preview-sounds.m4a"
    # KACH: menm spec + menm timeline + menm fichye son (dat / gwosè) → menm rezilta. Anvan: CHAK «Louvri nan
    # Navigatè» te refè miks FFmpeg la (10-36 s sou PC devlopè a, 2026-10-20) menm lè anyen pa t chanje.
    cues = events(spec, tl) if spec.get("sfx") else []
    key = _preview_key(spec, tl, base, cues)
    kf = out.with_suffix(".key")
    try:
        if out.is_file() and kf.is_file() and kf.read_text(encoding="utf-8") == key:
            return out
    except OSError:
        pass
    mix(spec, tl, total(tl, spec), out, base, {}, cache or Path(folder), cues)
    if out.is_file():
        try:
            kf.write_text(key, encoding="utf-8")
        except OSError:
            pass
        return out
    return None


_MEDIA_EXT = (".wav", ".mp3", ".m4a", ".aac", ".ogg", ".flac", ".opus", ".mp4", ".mov", ".webm", ".mkv", ".m4v")


_SOUND_SCENE_KEYS = ("id", "type", "sounds", "ambience", "audio", "src", "in", "out", "speed", "rig", "speaker")
_SOUND_TOP_KEYS = ("music", "sfx", "volume", "mix", "tracks")


def _preview_key(spec: dict, tl: list, base, cues=None) -> str:
    """Kle kach son aperçu a: SÈLMAN sa ki chanje son an (mizik, sfx, track, son sèn yo, timeline, evènman SFX yo,
    dat / gwosè fichye son yo) — yon tit / yon koulè ki chanje pa refè miks la."""
    files = []
    snd = {k: spec.get(k) for k in _SOUND_TOP_KEYS}
    snd["scenes"] = [{k: sc.get(k) for k in _SOUND_SCENE_KEYS} for sc in spec.get("scenes") or []]

    def walk(v):
        if isinstance(v, dict):
            for x in v.values():
                walk(x)
        elif isinstance(v, list):
            for x in v:
                walk(x)
        elif isinstance(v, str) and v.lower().endswith(_MEDIA_EXT):
            try:
                rp = Path(resolve(v, base))
                st = rp.stat()
                files.append((v, st.st_size, st.st_mtime_ns))
            except (OSError, ValueError, TypeError):
                files.append((v, 0, 0))
    walk(snd)
    tl_s = [{k: t.get(k) for k in ("id", "start", "dur", "clip", "rig")} for t in tl]
    blob = json.dumps([snd, tl_s, cues or [], sorted(files), PRE_MS, POST_S, "mix-v2"], sort_keys=True, default=str)
    return hashlib.sha1(blob.encode("utf-8")).hexdigest()



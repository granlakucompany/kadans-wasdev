def voice_fx(spec: dict) -> str:
    """Chenn netwayaj vwa a ak konpresè paramatrik, de-hummer 50/60Hz, denoise ak Vocal Clarity EQ."""
    v = spec.get("voice") if isinstance(spec.get("voice"), dict) else {}
    m = spec.get("mix") if isinstance(spec.get("mix"), dict) else {}
    c = v.get("compressor") or {}

    def num(k, d):
        try:
            return float(c.get(k, d))
        except (TypeError, ValueError):
            return d
    th = max(-60.0, min(0.0, num("threshold", -18)))
    ra = max(1.0, min(20.0, num("ratio", 3)))
    at = max(0.01, min(2000.0, num("attack", 5)))
    rl = max(1.0, min(9000.0, num("release", 140)))
    mu = max(0.0, min(24.0, num("makeup", 2)))
    comp = f"acompressor=threshold={th}dB:ratio={ra}:attack={at}:release={rl}:makeup={mu}"

    hum = v.get("hum_hz") if v.get("hum_hz") is not None else m.get("hum_hz")
    hum_f = _hum_filter(hum)

    dn = v.get("denoise") if v.get("denoise") is not None else m.get("denoise")
    dn_f = _denoise_filter(dn)

    preset = v.get("clarity_preset") or v.get("clarity") or m.get("clarity_preset") or m.get("clarity") or "podcast"
    eq_f = VOCAL_EQ_PRESETS.get(str(preset).lower(), VOCAL_EQ_PRESETS["podcast"])

    parts = []
    if hum_f:
        parts.append(hum_f)
    parts.append(dn_f)
    parts.append("deesser")
    parts.append(eq_f)
    parts.append(comp)
    parts.append("alimiter=limit=0.95")
    return ",".join(p for p in parts if p)


